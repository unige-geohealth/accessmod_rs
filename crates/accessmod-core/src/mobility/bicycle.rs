//! Bicycle speed model of `accessmod5-v1` and its lookup table (LUT).
//!
//! The model (physical cycling speed constrained by an empirical downhill
//! safety envelope, with hike-a-bike as a fallback) is specified in
//! `docker/alpine_base/modules/accessmod/bicycle-lut.md` and evaluated by
//! `generate-bicycle-lut.R` in AccessMod 5 `5.9.2-beta.6`. This module is now
//! the canonical source of the model:
//!
//! - [`model`] evaluates the exact equations in `f64`;
//! - [`generate_table`] samples them on the LUT grid, rounded as the AccessMod
//!   5 C header does, and `cargo xtask lut` commits the result;
//! - [`speed_kmh`] interpolates the committed `f32` table bilinearly in `f64`,
//!   as `am_bicycle_speed` (`mobility.h` l.54-108) does at run time.
//!
//! Slopes are ratios (`Δz / L`), speeds km/h.

use std::sync::LazyLock;

/// Lowest flat speed of the LUT grid, km/h.
pub const SPEED_MIN_KMH: f64 = 0.0;
/// Highest flat speed of the LUT grid, km/h. Faster scenario speeds are
/// clamped at run time (AccessMod 5 rejects them when encoding scenarios).
pub const SPEED_MAX_KMH: f64 = 100.0;
/// Flat-speed step of the LUT grid, km/h.
pub const SPEED_STEP_KMH: f64 = 0.5;
/// Number of flat-speed rows.
pub const SPEED_COUNT: usize = 201;
/// Lowest slope of the LUT grid (ratio).
pub const SLOPE_MIN: f64 = -1.2;
/// Highest slope of the LUT grid (ratio).
pub const SLOPE_MAX: f64 = 1.0;
/// Slope step of the LUT grid (ratio).
pub const SLOPE_STEP: f64 = 0.005;
/// Number of slope columns.
pub const SLOPE_COUNT: usize = 441;
/// Number of cells of the LUT, row-major (flat speed × slope).
pub const TABLE_LEN: usize = SPEED_COUNT * SLOPE_COUNT;

/// Committed LUT: `TABLE_LEN` little-endian `f32`, row-major, generated by
/// `cargo xtask lut` from [`generate_table`].
pub const TABLE_BYTES: &[u8] = include_bytes!("../../data/bicycle-lut-accessmod5-v1.f32le");

static TABLE: LazyLock<Vec<f32>> = LazyLock::new(|| {
    decode_table(TABLE_BYTES).expect("committed bicycle LUT has TABLE_LEN f32 values")
});

/// The committed LUT, row-major (flat speed × slope), km/h.
pub fn table() -> &'static [f32] {
    &TABLE
}

/// Bicycle speed in km/h at scenario flat speed `flat_speed_kmh` on `slope`,
/// interpolated bilinearly in the committed table.
///
/// Returns `0.0` for a non-positive flat speed or a non-finite slope. Speed
/// and slope outside the grid are clamped. Mirrors `am_bicycle_speed`
/// (`mobility.h` l.54-108), including its operation order, for bit parity.
pub fn speed_kmh(flat_speed_kmh: f64, slope: f64) -> f64 {
    interpolate(table(), flat_speed_kmh, slope)
}

/// Bilinear interpolation in `table` (row-major, `TABLE_LEN` values), see
/// [`speed_kmh`].
///
/// # Panics
///
/// If `table` is shorter than [`TABLE_LEN`].
pub fn interpolate(table: &[f32], flat_speed_kmh: f64, slope: f64) -> f64 {
    if !slope.is_finite() || !is_positive(flat_speed_kmh) {
        return 0.0;
    }
    let speed = flat_speed_kmh.min(SPEED_MAX_KMH);
    let slope = slope.clamp(SLOPE_MIN, SLOPE_MAX);

    let speed_position = (speed - SPEED_MIN_KMH) / SPEED_STEP_KMH;
    let slope_position = (slope - SLOPE_MIN) / SLOPE_STEP;
    let (speed_index, speed_fraction) = cell_index(speed_position, SPEED_COUNT);
    let (slope_index, slope_fraction) = cell_index(slope_position, SLOPE_COUNT);

    let at = |i: usize, j: usize| f64::from(table[i * SLOPE_COUNT + j]);
    let lower = linear(
        speed_fraction,
        at(speed_index, slope_index),
        at(speed_index + 1, slope_index),
    );
    let upper = linear(
        speed_fraction,
        at(speed_index, slope_index + 1),
        at(speed_index + 1, slope_index + 1),
    );
    linear(slope_fraction, lower, upper)
}

/// `x > 0`, false for NaN: a NaN speed is impassable.
fn is_positive(x: f64) -> bool {
    x > 0.0
}

/// Lower node index and fraction for a non-negative grid `position`; the last
/// node maps to the last interval with fraction 1.
fn cell_index(position: f64, count: usize) -> (usize, f64) {
    // `position` is finite and in [0, count - 1] after clamping, so the cast
    // neither saturates nor truncates a fraction away.
    let index = position.floor() as usize;
    if index >= count - 1 {
        (count - 2, 1.0)
    } else {
        (index, position - index as f64)
    }
}

/// `am_linear_interpolate(x, 0, y0, 1, y1)`: `y0 + (x − 0)·(y1 − y0)/(1 − 0)`.
fn linear(x: f64, y0: f64, y1: f64) -> f64 {
    y0 + (x - 0.0) * (y1 - y0) / (1.0 - 0.0)
}

/// Flat speed of LUT row `i`, km/h (R `seq(0, 100, by = 0.5)`).
pub fn grid_speed_kmh(i: usize) -> f64 {
    r_seq_value(SPEED_MIN_KMH, SPEED_MAX_KMH, SPEED_STEP_KMH, i)
}

/// Slope of LUT column `j` (R `seq(-1.2, 1, by = 0.005)`).
pub fn grid_slope(j: usize) -> f64 {
    r_seq_value(SLOPE_MIN, SLOPE_MAX, SLOPE_STEP, j)
}

/// Element `i` of R `seq(from, to, by)` with `by > 0`: `from + i·by`, capped
/// at `to`.
fn r_seq_value(from: f64, to: f64, by: f64, i: usize) -> f64 {
    (from + i as f64 * by).min(to)
}

/// Length of R `seq(from, to, by)` with `by > 0` (R's 1e-10 fuzz included).
fn r_seq_len(from: f64, to: f64, by: f64) -> usize {
    ((to - from) / by + 1e-10).floor() as usize + 1
}

/// Sample the exact model on the LUT grid.
///
/// Each value is rounded as the AccessMod 5 generator writes it to its C
/// header (`sprintf("%.8ff")`, then parsed as `float`), so the table matches
/// the oracle table cell by cell.
pub fn generate_table() -> Vec<f32> {
    let mut values = Vec::with_capacity(TABLE_LEN);
    for i in 0..SPEED_COUNT {
        let flat_speed = grid_speed_kmh(i);
        for j in 0..SLOPE_COUNT {
            values.push(round_like_c_header(model::speed_kmh(
                flat_speed,
                grid_slope(j),
            )));
        }
    }
    values
}

/// Round to 8 decimals, then to the nearest `f32`, as a C compiler reads the
/// `%.8f` literals of `bicycle-lut.generated.h`.
fn round_like_c_header(value: f64) -> f32 {
    format!("{value:.8}")
        .parse::<f32>()
        .expect("a formatted finite f64 parses as f32")
}

/// Serialise a table as little-endian `f32` bytes.
pub fn encode_table(table: &[f32]) -> Vec<u8> {
    table.iter().flat_map(|v| v.to_le_bytes()).collect()
}

/// Parse little-endian `f32` bytes; `None` unless exactly [`TABLE_LEN`]
/// values.
pub fn decode_table(bytes: &[u8]) -> Option<Vec<f32>> {
    if bytes.len() != TABLE_LEN * 4 {
        return None;
    }
    Some(
        bytes
            .chunks_exact(4)
            .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
            .collect(),
    )
}

/// Interpolation error of a table against the exact model.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct InterpolationError {
    /// Number of sampled points.
    pub samples: usize,
    /// Maximum absolute error, km/h.
    pub max_kmh: f64,
    /// 99th percentile of the absolute error (R quantile type 7), km/h.
    pub p99_kmh: f64,
}

/// Maximum accepted interpolation error, km/h (AccessMod 5 generator).
pub const MAX_ERROR_KMH: f64 = 0.35;
/// Maximum accepted 99th-percentile interpolation error, km/h.
pub const P99_ERROR_KMH: f64 = 0.05;

impl InterpolationError {
    /// Whether the error is within the AccessMod 5 acceptance limits.
    pub fn is_acceptable(&self) -> bool {
        self.max_kmh <= MAX_ERROR_KMH && self.p99_kmh <= P99_ERROR_KMH
    }
}

/// Error of [`interpolate`] over `table` at every cell centre of the
/// operational range (1–40 km/h, all slopes), as checked by the AccessMod 5
/// generator. Unlike AccessMod 5, which checks its `f64` table, this checks
/// the `f32` table actually used at run time.
pub fn interpolation_error(table: &[f32]) -> InterpolationError {
    let speed_from = 1.25;
    let speed_to = 39.75;
    let slope_from = SLOPE_MIN + SLOPE_STEP / 2.0;
    let slope_to = SLOPE_MAX - SLOPE_STEP / 2.0;
    let speed_len = r_seq_len(speed_from, speed_to, SPEED_STEP_KMH);
    let slope_len = r_seq_len(slope_from, slope_to, SLOPE_STEP);

    let mut errors = Vec::with_capacity(speed_len * slope_len);
    for i in 0..speed_len {
        let flat_speed = r_seq_value(speed_from, speed_to, SPEED_STEP_KMH, i);
        for j in 0..slope_len {
            let slope = r_seq_value(slope_from, slope_to, SLOPE_STEP, j);
            let exact = model::speed_kmh(flat_speed, slope);
            errors.push((exact - interpolate(table, flat_speed, slope)).abs());
        }
    }
    errors.sort_by(f64::total_cmp);
    InterpolationError {
        samples: errors.len(),
        max_kmh: errors.last().copied().unwrap_or(0.0),
        p99_kmh: quantile_type7(&errors, 0.99),
    }
}

/// R `quantile(x, p, type = 7)` of sorted, non-empty `x`.
fn quantile_type7(sorted: &[f64], p: f64) -> f64 {
    if sorted.is_empty() {
        return 0.0;
    }
    let h = (sorted.len() - 1) as f64 * p;
    let lo = h.floor() as usize;
    let hi = (lo + 1).min(sorted.len() - 1);
    sorted[lo] + (h - lo as f64) * (sorted[hi] - sorted[lo])
}

/// Exact bicycle model, `f64`, no table.
pub mod model {
    use super::is_positive;

    /// Fixed physical assumptions of `accessmod5-v1` (`bicycle-lut.md`).
    #[derive(Debug, Clone, Copy, PartialEq)]
    pub struct Parameters {
        /// Rider mass, kg.
        pub rider_mass_kg: f64,
        /// Bicycle mass, kg.
        pub bicycle_mass_kg: f64,
        /// Gravitational acceleration, m/s².
        pub gravity_m_s2: f64,
        /// Rolling-resistance coefficient.
        pub rolling_resistance: f64,
        /// Frontal area, m².
        pub frontal_area_m2: f64,
        /// Head wind, m/s.
        pub wind_speed_m_s: f64,
        /// Air temperature, °C.
        pub temperature_c: f64,
        /// Elevation used for air density, m.
        pub elevation_m: f64,
        /// Drivetrain efficiency.
        pub transmission_efficiency: f64,
        /// Flat walking speed when pushing the bicycle, km/h.
        pub hike_flat_speed_kmh: f64,
        /// Numerical floor of the hike-a-bike speed, km/h.
        pub hike_min_speed_kmh: f64,
    }

    /// Parameters of `accessmod5-v1` (`generate-bicycle-lut.R`, AccessMod 5
    /// `5.9.2-beta.6`).
    pub const PARAMETERS: Parameters = Parameters {
        rider_mass_kg: 80.0,
        bicycle_mass_kg: 15.0,
        gravity_m_s2: 9.8,
        rolling_resistance: 0.012,
        frontal_area_m2: 0.445,
        wind_speed_m_s: 0.0,
        temperature_c: 20.0,
        elevation_m: 500.0,
        transmission_efficiency: 0.90,
        hike_flat_speed_kmh: 3.2,
        hike_min_speed_kmh: 0.1,
    };

    /// Downhill safety envelope anchors: (slope, maximum riding factor of
    /// the flat speed), linearly interpolated, ascending slope.
    ///
    /// −5.5 % and −10 %: Flügel, S., Hulleberg, N., Fyhri, A., Weber, C. &
    /// Ævarsson, G. (2019). Empirical speed models for cycling in the Oslo
    /// road network. Transportation 46, 1395–1419. −25 % (not ridable) and
    /// 0 % (flat speed) are AccessMod assumptions.
    pub const ENVELOPE: [(f64, f64); 4] = [(-0.25, 0.0), (-0.10, 1.05), (-0.055, 1.20), (0.0, 1.0)];

    /// Branches of the model at one (flat speed, slope), km/h.
    #[derive(Debug, Clone, Copy, PartialEq)]
    pub struct Components {
        /// Speed predicted by the force balance at equivalent power.
        pub physics: f64,
        /// Downhill safety cap; `+∞` on flat ground and uphill.
        pub safety_envelope: f64,
        /// `min(physics, safety_envelope)`.
        pub ride: f64,
        /// Pushing the bicycle (Tobler).
        pub hike: f64,
        /// `max(ride, hike)`: the model speed.
        pub selected: f64,
    }

    /// Air density at the fixed temperature and elevation, kg/m³.
    fn air_density() -> f64 {
        let p = PARAMETERS;
        (1.293 - 0.00426 * p.temperature_c) * (-p.elevation_m / 7000.0).exp()
    }

    /// Weight of rider and bicycle, N.
    fn weight_force() -> f64 {
        let p = PARAMETERS;
        p.gravity_m_s2 * (p.rider_mass_kg + p.bicycle_mass_kg)
    }

    /// Aerodynamic drag coefficient `½·A·ρ`, kg/m.
    fn air_resistance() -> f64 {
        0.5 * PARAMETERS.frontal_area_m2 * air_density()
    }

    /// Pedalling power that sustains `flat_speed_kmh` on flat ground, W.
    pub fn equivalent_power_w(flat_speed_kmh: f64) -> f64 {
        let p = PARAMETERS;
        let velocity = flat_speed_kmh / 3.6;
        let resistance = weight_force() * p.rolling_resistance;
        let air_velocity = velocity + p.wind_speed_m_s;
        (velocity * resistance + velocity * (air_velocity * air_velocity) * air_resistance())
            / p.transmission_efficiency
    }

    /// Speed on `slope` at the equivalent power of `flat_speed_kmh`, km/h.
    ///
    /// Solves `v·(½Aρ·(v + w)² + W·(slope + Crr)) = η·P` for `v > 0`. With
    /// `η·P > 0` the residual is negative at 0 and the cubic has exactly one
    /// positive root, found by bisection to full `f64` precision
    /// (AccessMod 5 uses `uniroot` with `tol = 1e-11` m/s).
    pub fn physics_speed_kmh(flat_speed_kmh: f64, slope: f64) -> f64 {
        if !is_positive(flat_speed_kmh) {
            return 0.0;
        }
        let p = PARAMETERS;
        let target = p.transmission_efficiency * equivalent_power_w(flat_speed_kmh);
        let resistance = weight_force() * (slope + p.rolling_resistance);
        let air = air_resistance();
        let residual = |velocity: f64| {
            let air_velocity = velocity + p.wind_speed_m_s;
            velocity * (air * (air_velocity * air_velocity) + resistance) - target
        };

        let mut low = 0.0_f64;
        let mut high = (flat_speed_kmh / 3.6).max(1.0);
        while residual(high) < 0.0 {
            high *= 2.0;
        }
        loop {
            let mid = low + (high - low) / 2.0;
            if mid <= low || mid >= high {
                break;
            }
            if residual(mid) < 0.0 {
                low = mid;
            } else {
                high = mid;
            }
        }
        let root = if residual(low).abs() <= residual(high).abs() {
            low
        } else {
            high
        };
        root * 3.6
    }

    /// Maximum riding factor of the flat speed on `slope`; `+∞` for
    /// `slope ≥ 0`, 0 at or below −25 %.
    pub fn safety_factor(slope: f64) -> f64 {
        if slope >= 0.0 {
            return f64::INFINITY;
        }
        let (first_slope, first_factor) = ENVELOPE[0];
        if slope <= first_slope {
            return first_factor;
        }
        for pair in ENVELOPE.windows(2) {
            let ((x0, y0), (x1, y1)) = (pair[0], pair[1]);
            if slope == x0 {
                return y0;
            }
            if slope == x1 {
                return y1;
            }
            if slope > x0 && slope < x1 {
                // R `approx` linear rule, same operation order.
                return y0 + (y1 - y0) * ((slope - x0) / (x1 - x0));
            }
        }
        unreachable!("slope in (-0.25, 0) lies in one envelope interval")
    }

    /// Hike-a-bike speed: Tobler's curve at `min(flat, 3.2)` km/h with a
    /// `min(flat, 0.1)` km/h floor, km/h.
    pub fn hike_speed_kmh(flat_speed_kmh: f64, slope: f64) -> f64 {
        if !is_positive(flat_speed_kmh) {
            return 0.0;
        }
        let p = PARAMETERS;
        let flat_hike = flat_speed_kmh.min(p.hike_flat_speed_kmh);
        let minimum = flat_speed_kmh.min(p.hike_min_speed_kmh);
        minimum.max(flat_hike * (0.175 - 3.5 * (slope + 0.05).abs()).exp())
    }

    /// All branches of the model at one point.
    pub fn components(flat_speed_kmh: f64, slope: f64) -> Components {
        if !is_positive(flat_speed_kmh) {
            return Components {
                physics: 0.0,
                safety_envelope: 0.0,
                ride: 0.0,
                hike: 0.0,
                selected: 0.0,
            };
        }
        let physics = physics_speed_kmh(flat_speed_kmh, slope);
        let safety_envelope = if slope < 0.0 {
            flat_speed_kmh * safety_factor(slope)
        } else {
            f64::INFINITY
        };
        let ride = physics.min(safety_envelope);
        let hike = hike_speed_kmh(flat_speed_kmh, slope);
        Components {
            physics,
            safety_envelope,
            ride,
            hike,
            selected: ride.max(hike),
        }
    }

    /// Model speed, km/h.
    pub fn speed_kmh(flat_speed_kmh: f64, slope: f64) -> f64 {
        components(flat_speed_kmh, slope).selected
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn grid_matches_constants() {
        assert_eq!(
            r_seq_len(SPEED_MIN_KMH, SPEED_MAX_KMH, SPEED_STEP_KMH),
            SPEED_COUNT
        );
        assert_eq!(r_seq_len(SLOPE_MIN, SLOPE_MAX, SLOPE_STEP), SLOPE_COUNT);
        assert_eq!(grid_speed_kmh(SPEED_COUNT - 1), SPEED_MAX_KMH);
        assert_eq!(grid_slope(SLOPE_COUNT - 1), SLOPE_MAX);
        assert_eq!(grid_slope(0), SLOPE_MIN);
    }

    #[test]
    fn equivalent_power_matches_documented_values() {
        // bicycle-lut.md: about 97 W at 18 km/h, 117 W at 20, 139 W at 22.
        for (speed, watts) in [(18.0, 97.0), (20.0, 117.0), (22.0, 139.0)] {
            let p = model::equivalent_power_w(speed);
            assert!((p - watts).abs() < 1.0, "{speed} km/h: {p} W");
        }
    }

    #[test]
    fn physics_returns_flat_speed_on_flat_ground() {
        for speed in [0.5, 6.0, 20.0, 45.0, 100.0] {
            let v = model::physics_speed_kmh(speed, 0.0);
            assert!((v - speed).abs() < 1e-9 * speed, "{speed}: {v}");
        }
    }

    #[test]
    fn physics_slows_uphill_and_speeds_up_downhill() {
        let flat = model::physics_speed_kmh(20.0, 0.0);
        assert!(model::physics_speed_kmh(20.0, 0.05) < flat);
        assert!(model::physics_speed_kmh(20.0, -0.05) > flat);
    }

    #[test]
    fn envelope_anchors() {
        assert_eq!(model::safety_factor(0.0), f64::INFINITY);
        assert_eq!(model::safety_factor(-0.055), 1.20);
        assert_eq!(model::safety_factor(-0.10), 1.05);
        assert_eq!(model::safety_factor(-0.25), 0.0);
        assert_eq!(model::safety_factor(-0.9), 0.0);
        let mid = model::safety_factor(-0.0275);
        assert!((mid - 1.10).abs() < 1e-12, "{mid}");
    }

    #[test]
    fn hike_floor_never_raises_a_tiny_scenario_speed() {
        assert_eq!(model::hike_speed_kmh(0.05, 1.0), 0.05);
        assert_eq!(model::hike_speed_kmh(10.0, 1.0), 0.1);
    }

    #[test]
    fn selected_is_flat_speed_on_flat_ground() {
        let c = model::components(20.0, 0.0);
        assert_eq!(c.safety_envelope, f64::INFINITY);
        assert!((c.selected - 20.0).abs() < 1e-9);
    }

    #[test]
    fn steep_descent_falls_back_to_hiking() {
        let c = model::components(20.0, -0.3);
        assert_eq!(c.ride, 0.0);
        assert_eq!(c.selected, c.hike);
    }

    #[test]
    fn interpolation_returns_node_values() {
        // Grid slopes are not exact multiples of the step in binary, so a
        // node may land at the far end of the previous interval: compare
        // with a tolerance, not bit for bit.
        let t = table();
        for (i, j) in [(1, 0), (40, 240), (40, 200), (200, 440), (37, 13)] {
            let v = interpolate(t, grid_speed_kmh(i), grid_slope(j));
            let expected = f64::from(t[i * SLOPE_COUNT + j]);
            assert!(
                (v - expected).abs() <= 1e-9 * expected.max(1.0),
                "node ({i}, {j})"
            );
        }
    }

    #[test]
    fn interpolation_guards() {
        assert_eq!(speed_kmh(0.0, 0.0), 0.0);
        assert_eq!(speed_kmh(-3.0, 0.0), 0.0);
        assert_eq!(speed_kmh(f64::NAN, 0.0), 0.0);
        assert_eq!(speed_kmh(20.0, f64::NAN), 0.0);
        assert_eq!(speed_kmh(20.0, f64::INFINITY), 0.0);
        assert_eq!(speed_kmh(150.0, 0.0), speed_kmh(100.0, 0.0));
        assert_eq!(speed_kmh(20.0, 3.0), speed_kmh(20.0, SLOPE_MAX));
        assert_eq!(speed_kmh(20.0, -3.0), speed_kmh(20.0, SLOPE_MIN));
    }

    #[test]
    fn committed_table_is_up_to_date_and_accurate() {
        let generated = generate_table();
        assert!(
            generated
                .iter()
                .zip(table())
                .all(|(a, b)| a.to_bits() == b.to_bits()),
            "committed LUT is out of date: run `cargo xtask lut`"
        );
        let error = interpolation_error(table());
        assert!(error.is_acceptable(), "{error:?}");
    }

    #[test]
    fn quantile_type7_matches_r() {
        // R: quantile(c(1, 2, 3, 4, 10), 0.99) = 9.76
        let q = quantile_type7(&[1.0, 2.0, 3.0, 4.0, 10.0], 0.99);
        assert!((q - 9.76).abs() < 1e-12, "{q}");
    }

    #[test]
    fn round_like_c_header_rounds_to_eight_decimals_first() {
        assert_eq!(round_like_c_header(0.123_456_784_9), 0.123_456_78_f32);
        assert_eq!(round_like_c_header(0.0), 0.0);
    }
}
