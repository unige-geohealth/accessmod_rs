// Write references/inventory.md from references/index.json and the
// per-screen meta.json files: screen → AM5 sources → icons → i18n keys.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const REF = resolve(process.env.OUT_DIR ?? join(here, "../../references"));
const index = JSON.parse(readFileSync(join(REF, "index.json"), "utf8"));

// keys of the shell, listed once instead of per screen
const shell = (k) => k.startsWith("main_ui_");

const lines = [
  "# AM5 screen inventory",
  "",
  `Generated by \`scripts/capture/inventory.mjs\` from a capture of ${index.url} (project \`${index.project}\`, ${index.capturedAt.slice(0, 10)}).`,
  "Each screen folder in `screens/<id>/` holds `en|fr|es|pt.png` (1440 wide, full page), `dom.html` (visible DOM, `data-amt_id` = i18n key), `aria.yaml` and `meta.json` (all keys with their four translations).",
  "Paths in *Sources* are relative to the AM5 repository.",
  "",
  "| Screen | id | Height | Sources |",
  "|---|---|---|---|",
  ...index.screens.map((s) => `| ${s.name} | [\`${s.id}\`](screens/${s.id}/en.png) | ${s.page.height}px | ${s.source.map((p) => `\`${p}\``).join("<br>")} |`),
  "",
];

const shellKeys = new Map();
for (const s of index.screens) {
  const meta = JSON.parse(readFileSync(join(REF, "screens", s.id, "meta.json"), "utf8"));
  for (const k of meta.i18n.filter((k) => shell(k.key))) shellKeys.set(k.key, k.text);
  lines.push(
    `## ${s.name}`,
    "",
    `\`${s.id}\` · steps: ${meta.steps.map((st) => `\`${JSON.stringify(st)}\``).join(" → ")}`,
    "",
    `Icons: ${meta.icons.map((i) => `\`${i}\``).join(" ") || "—"}`,
    "",
    "| i18n key | en |",
    "|---|---|",
    ...meta.i18n.filter((k) => !shell(k.key)).map((k) => `| \`${k.key}\` | ${k.text.replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 120)} |`),
    "",
  );
}
lines.push("## Shell (every screen)", "", "| i18n key | en |", "|---|---|", ...[...shellKeys].map(([k, t]) => `| \`${k}\` | ${t} |`), "");

writeFileSync(join(REF, "inventory.md"), lines.join("\n"));
console.log(`inventory: ${index.screens.length} screens`);
